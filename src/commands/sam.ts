import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { readdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { bold, dim, fail, info, ok, step, warn } from '../lib/log.js';
import type { RunContext } from './run.js';

/** The sam/ directory shipped inside `@govuk-connect/dev` (raw files: docker-compose, wrapper). */
const SAM_PKG_DIR = fileURLToPath(new URL('../../sam/', import.meta.url));

/** The compiled sam/ JS files in dist/. */
const SAM_DIST_DIR = fileURLToPath(new URL('../sam/', import.meta.url));

export const SAM_USAGE = `${bold('dev sam:<command>')} - local Lambda development with SAM + LocalStack

Usage
  dev sam:synth [options]  Synthesise the CDK app with SAM_LOCAL=true
  dev sam:start [options]  Start LocalStack + SAM local API (synth → up → sam local)
  dev sam:stop  [options]  Tear down LocalStack and clean up Lambda containers

Options
  --dir <name>  CDK directory, relative to the package (default: cdk)
  --cwd <path>  Run against this package instead of the current directory
  --help        Show this message

${dim('The SAM infrastructure (CDK Aspect, esbuild wrapper, docker-compose,')}
${dim('init-local-resources) all live inside @govuk-connect/dev. Your CDK')}
${dim('app just needs the SAM_LOCAL gate in bin/app.ts (generated by')}
${dim('`dev cdk:init --sam`) and sam:source-entry metadata on your Lambdas.')}
`;

function parseSamArgs(argv: readonly string[]) {
  return parseArgs({
    args: [...argv],
    options: {
      dir: { type: 'string' },
      help: { type: 'boolean', short: 'h' },
    },
    allowPositionals: false,
  });
}

function cdkDir(cwd: string, dir?: string): string {
  const target = join(cwd, dir ?? 'cdk');
  if (!existsSync(target)) {
    fail(
      `${dir ?? 'cdk'}/ does not exist in this package.`,
      'Run `dev cdk:init --sam` first to scaffold the CDK app.',
    );
  }
  return target;
}

function resolveSamCli(): string {
  const result = spawnSync('sam', ['--version'], { encoding: 'utf8' });
  if (result.error !== undefined || (result.status ?? 1) !== 0) {
    fail(
      'SAM CLI is not installed.',
      'Install it: brew install aws-sam-cli (macOS) or pip install aws-sam-cli',
    );
  }
  return 'sam';
}

export async function runSamSynth(argv: readonly string[], context: RunContext): Promise<number> {
  const { values } = parseSamArgs(argv);

  if (values.help === true) {
    info(SAM_USAGE);
    return 0;
  }

  const target = cdkDir(context.cwd, values.dir);
  const samOut = join(target, '.aws-sam');

  step('Cleaning previous SAM output');
  await rm(samOut, { recursive: true, force: true });

  const cdk = join(context.cwd, 'node_modules', '.bin', 'cdk');
  if (!existsSync(cdk)) {
    fail('The CDK CLI is not installed for this package.', 'Run `pnpm install` first.');
  }

  step('Synthesising with SAM_LOCAL=true');
  const result = spawnSync(cdk, ['synth', '-o', samOut], {
    cwd: target,
    stdio: 'inherit',
    env: { ...process.env, SAM_LOCAL: 'true', SAM_REPO_ROOT: context.cwd },
  });

  if (result.error !== undefined) fail(`Failed to run cdk synth: ${result.error.message}`);
  if ((result.status ?? 1) !== 0) return result.status ?? 1;

  ok(`Synthesised to ${join(values.dir ?? 'cdk', '.aws-sam')}`);
  await prepareLocalTemplate(samOut);
  return 0;
}

const COMBINED_TEMPLATE = 'sam-combined.template.json';

function stackTemplates(files: readonly string[]): string[] {
  return files.filter((f) => f.endsWith('.template.json') && f !== COMBINED_TEMPLATE);
}

/**
 * Rewrites every stack template for LocalStack, so `sam local invoke -t <stack>` works
 * on its own, then merges them - `sam local start-api` takes a single template.
 */
async function prepareLocalTemplate(samOut: string): Promise<void> {
  const stacks = stackTemplates(await readdir(samOut));
  if (stacks.length === 0) {
    fail('No CloudFormation template found after synth.', 'Check your CDK app.');
  }

  for (const file of stacks) {
    const path = join(samOut, file);
    const tpl = JSON.parse(readFileSync(path, 'utf8')) as CfnTemplate;
    rewriteLocalRefs(tpl);
    writeFileSync(path, JSON.stringify(tpl, null, 2), 'utf8');
  }

  if (stacks.length > 1) {
    mergeTemplates(
      stacks.map((f) => join(samOut, f)),
      join(samOut, COMBINED_TEMPLATE),
    );
    ok(`Merged ${stacks.length} stacks into ${COMBINED_TEMPLATE}`);
  }
}

/** The template `sam local start-api` should serve, as left by `prepareLocalTemplate`. */
async function localTemplatePath(samOut: string): Promise<string> {
  const combined = join(samOut, COMBINED_TEMPLATE);
  if (existsSync(combined)) return combined;
  return join(samOut, stackTemplates(await readdir(samOut))[0] as string);
}

export async function runSamStart(argv: readonly string[], context: RunContext): Promise<number> {
  const { values } = parseSamArgs(argv);

  if (values.help === true) {
    info(SAM_USAGE);
    return 0;
  }

  const target = cdkDir(context.cwd, values.dir);

  // Synth
  const synthResult = await runSamSynth(argv, context);
  if (synthResult !== 0) return synthResult;

  const samOut = join(target, '.aws-sam');
  const template = await localTemplatePath(samOut);

  // Docker compose up (using the dev package's docker-compose.yml)
  const compose = join(SAM_PKG_DIR, 'docker-compose.yml');
  step('Starting LocalStack');
  spawnSync('docker', ['compose', '-f', compose, 'down'], { stdio: 'inherit' });
  const upResult = spawnSync('docker', ['compose', '-f', compose, 'up', '-d'], {
    stdio: 'inherit',
  });
  if ((upResult.status ?? 1) !== 0) fail('Failed to start LocalStack.');

  // Init local resources (using the dev package's init script)
  step('Provisioning local resources');
  const initScript = join(SAM_DIST_DIR, 'init-local-resources.js');
  const initResult = spawnSync('node', [initScript], {
    cwd: context.cwd,
    stdio: 'inherit',
    env: { ...process.env, SAM_OUT_DIR: samOut },
  });
  if ((initResult.status ?? 1) !== 0) {
    warn('Failed to provision local resources (LocalStack may still be starting).');
  }

  // SAM local start-api
  const sam = resolveSamCli();
  step('Starting SAM local API');
  info(dim('  Press Ctrl+C to stop'));
  const samResult = spawnSync(
    sam,
    [
      'local',
      'start-api',
      '-t',
      template,
      '--docker-network',
      'sam-local',
      '--region',
      'eu-west-2',
    ],
    {
      cwd: context.cwd,
      stdio: 'inherit',
      env: {
        ...process.env,
        DOCKER_HOST: `unix://${process.env['HOME']}/.docker/run/docker.sock`,
      },
    },
  );

  return samResult.status ?? 1;
}

export async function runSamStop(argv: readonly string[], _context: RunContext): Promise<number> {
  const { values } = parseSamArgs(argv);

  if (values.help === true) {
    info(SAM_USAGE);
    return 0;
  }

  const compose = join(SAM_PKG_DIR, 'docker-compose.yml');

  step('Stopping LocalStack');
  spawnSync('docker', ['compose', '-f', compose, 'down'], { stdio: 'inherit' });

  step('Cleaning up Lambda containers');
  const ps = spawnSync('docker', ['ps', '-a', '--format', '{{.ID}} {{.Image}}'], {
    encoding: 'utf8',
  });
  const lambdaContainers = (ps.stdout ?? '')
    .split('\n')
    .filter((line) => line.includes('public.ecr.aws/lambda'))
    .map((line) => line.split(' ')[0] as string);

  if (lambdaContainers.length > 0) {
    spawnSync('docker', ['rm', '-f', ...lambdaContainers], { stdio: 'inherit' });
    ok(`Removed ${lambdaContainers.length} Lambda container(s)`);
  }

  ok('Stopped');
  return 0;
}

interface CfnTemplate {
  Resources?: Record<string, unknown>;
  Outputs?: Record<string, unknown>;
  Parameters?: Record<string, unknown>;
  Conditions?: Record<string, unknown>;
  Metadata?: Record<string, unknown>;
  [key: string]: unknown;
}

function mergeTemplates(paths: string[], outPath: string): void {
  const merged: CfnTemplate = {
    AWSTemplateFormatVersion: '2010-09-09',
    Transform: 'AWS::Serverless-2016-10-31',
    Resources: {},
    Outputs: {},
  };

  for (const p of paths) {
    const tpl = JSON.parse(readFileSync(p, 'utf8')) as CfnTemplate;
    // oxlint-disable-next-line typescript/no-non-null-assertion
    Object.assign(merged.Resources!, tpl.Resources ?? {});
    // oxlint-disable-next-line typescript/no-non-null-assertion
    Object.assign(merged.Outputs!, tpl.Outputs ?? {});
  }

  writeFileSync(outPath, JSON.stringify(merged, null, 2), 'utf8');
}

/**
 * SAM resolves `{Ref: X}` to the bare logical id, which no SDK client can use. Point
 * the Refs that matter at what LocalStack actually serves: a queue URL, and the
 * alias `init-local-resources` gives each KMS key (LocalStack picks its own key ids).
 */
function rewriteLocalRefs(template: CfnTemplate): void {
  const resources = template.Resources ?? {};

  const localValues = new Map<string, string>();
  for (const [id, resource] of Object.entries(resources)) {
    const r = resource as { Type?: string; Properties?: { QueueName?: string } };
    if (r.Type === 'AWS::SQS::Queue') {
      const name = r.Properties?.QueueName ?? id;
      localValues.set(id, `http://localstack:4566/000000000000/${name}`);
    }
    if (r.Type === 'AWS::KMS::Key') localValues.set(id, `alias/${id}`);
  }

  if (localValues.size === 0) return;

  for (const resource of Object.values(resources)) {
    const r = resource as { Type?: string; Properties?: Record<string, unknown> };
    if (r.Type !== 'AWS::Lambda::Function') continue;

    const env = r.Properties?.['Environment'] as
      | { Variables?: Record<string, unknown> }
      | undefined;
    if (!env?.Variables) continue;

    for (const [key, val] of Object.entries(env.Variables)) {
      if (typeof val === 'object' && val !== null && 'Ref' in val) {
        const local = localValues.get((val as { Ref: string }).Ref);
        if (local !== undefined) env.Variables[key] = local;
      }
    }
  }
}
